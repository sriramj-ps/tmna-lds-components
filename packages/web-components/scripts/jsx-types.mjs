// Generates JSX types for every LDS custom element from the Stencil-built custom-elements.json.
// Shipped as `@tmna-cx-design-system/web-components/jsx`, so React 19 (and Preact or Solid) apps
// can use <lds-button variant="secondary"> directly, with autocomplete and errors for bad values.
import { readFileSync, writeFileSync } from 'node:fs';
import { generateJsxTypes } from '@wc-toolkit/jsx-types';

const OUT = 'dist/jsx/index.d.ts';
const manifest = JSON.parse(readFileSync('dist/custom-elements.json', 'utf8'));

generateJsxTypes(manifest, {
  outdir: './dist/jsx',
  fileName: 'index.d.ts',
  // Prop types come straight from the manifest (the same unions as the components)
  useCemTypes: true,
  // `e.detail` and `e.target` typed per component event
  stronglyTypedEvents: true,
});

// The generator imports each class from its source path (src/...tsx), which isn't published.
// Point `ref` types at the element interfaces Stencil ships instead (HTMLLdsButtonElement).
let types = readFileSync(OUT, 'utf8');
const imports = [...types.matchAll(/^import type \{ (\w+) \} from "src\/[^"]+";\n/gm)];
if (imports.length === 0) throw new Error(`${OUT}: expected component imports to rewrite`);
for (const [line, name] of imports) {
  types = types.replace(line, `type ${name} = HTML${name}Element;\n`);
}
types = `// Generated by scripts/jsx-types.mjs. Do not edit.\nimport type {} from "../types/components";\n${types}`;
writeFileSync(OUT, types);
console.log(`${OUT}: JSX types for ${imports.length} component(s)`);
